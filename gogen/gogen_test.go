// structFieldType parses src and returns the Go type expression of
// structName.fieldName, as rendered by go/types.ExprString.
func structFieldType(t *testing.T, src []byte, structName, fieldName string) string {
	t.Helper()
	f, err := parser.ParseFile(token.NewFileSet(), "gen.go", src, 0)
	if err != nil {
		t.Fatalf("parse generated source: %v\n%s", err, src)
	}
	got := ""
	ast.Inspect(f, func(n ast.Node) bool {
		ts, ok := n.(*ast.TypeSpec)
		if !ok || ts.Name.Name != structName {
			return true
		}
		st, ok := ts.Type.(*ast.StructType)
		if !ok {
			return true
		}
		for _, fld := range st.Fields.List {
			if len(fld.Names) == 1 && fld.Names[0].Name == fieldName {
				got = types.ExprString(fld.Type)
			}
		}
		return false
	})
	if got == "" {
		t.Fatalf("field %s.%s not found in:\n%s", structName, fieldName, src)
	}
	return got
}

// optionalFieldType generates types for a single optional "field" property
// described by propSchema and returns that field's Go type. A "Ref" object
// definition is always available for $ref cases.
func optionalFieldType(t *testing.T, propSchema string) string {
	t.Helper()
	schema := `{
		"$schema": "http://json-schema.org/draft-07/schema#",
		"type": "object",
		"definitions": {"Ref": {"type": "object", "properties": {"a": {"type": "string"}}}},
		"properties": {"field": ` + propSchema + `}
	}`
	src, err := gogen.Generate([]byte(schema), gogen.WithRootType("Root"))
	if err != nil {
		t.Fatalf("Generate(%s): %v", propSchema, err)
	}
	return structFieldType(t, src, "Root", "Field")
}

// TestGenerate_typeMatrix exercises the type mapping across the full range
// of JSON Schema constructs the generator recognizes, plus the constructs it
// deliberately degrades to any (unions, oneOf/anyOf/not, conditionals,
// boolean schemas, empty schemas). Fields here are optional, so scalars are
// value types and object references are pointers.
func TestGenerate_typeMatrix(t *testing.T) {
	cases := []struct {
		name string
		prop string
		want string
	}{
		// Scalars.
		{"string", `{"type":"string"}`, "string"},
		{"integer", `{"type":"integer"}`, "int"},
		{"number", `{"type":"number"}`, "float64"},
		{"boolean", `{"type":"boolean"}`, "bool"},

		// Arrays.
		{"array_of_string", `{"type":"array","items":{"type":"string"}}`, "[]string"},
		{"array_of_integer", `{"type":"array","items":{"type":"integer"}}`, "[]int"},
		{"array_of_ref", `{"type":"array","items":{"$ref":"#/definitions/Ref"}}`, "[]Ref"},
		{"array_no_items", `{"type":"array"}`, "[]any"},
		{"array_tuple_items", `{"type":"array","items":[{"type":"string"},{"type":"integer"}]}`, "[]any"},

		// Objects / maps.
		{"map_string", `{"type":"object","additionalProperties":{"type":"string"}}`, "map[string]string"},
		{"map_ref", `{"type":"object","additionalProperties":{"$ref":"#/definitions/Ref"}}`, "map[string]Ref"},
		{"map_addl_true", `{"type":"object","additionalProperties":true}`, "map[string]any"},
		{"free_object", `{"type":"object"}`, "map[string]any"},
		{"pattern_properties", `{"type":"object","patternProperties":{"^x":{"type":"integer"}}}`, "map[string]int"},

		// References.
		{"ref", `{"$ref":"#/definitions/Ref"}`, "*Ref"},

		// enum / const inference.
		{"enum_string", `{"enum":["a","b"]}`, "string"},
		{"enum_number", `{"enum":[1,2]}`, "float64"},
		{"const_string", `{"const":"x"}`, "string"},
		{"const_bool", `{"const":true}`, "bool"},

		// Type unions. A scalar + null union is the presence-carrying mapping:
		// the pointer distinguishes "absent (or null)" from the zero value —
		// the contract keywords like a spec's `minimum` rely on (0 declared
		// vs no bound at all). Containers stay bare: nil is already absence.
		{"nullable_string", `{"type":["string","null"]}`, "*string"},
		{"nullable_integer", `{"type":["integer","null"]}`, "*int"},
		{"nullable_number", `{"type":["number","null"]}`, "*float64"},
		{"nullable_boolean", `{"type":["boolean","null"]}`, "*bool"},
		{"nullable_array", `{"type":["array","null"],"items":{"type":"string"}}`, "[]string"},
		{"nullable_items", `{"type":"array","items":{"type":["integer","null"]}}`, "[]*int"},
		{"nullable_map_value", `{"type":"object","additionalProperties":{"type":["string","null"]}}`, "map[string]*string"},
		{"union_multi", `{"type":["string","integer"]}`, "any"},

		// The anyOf nullable form — what generate.WithNullablePointers emits
		// for a Go pointer — round-trips back to the pointer, either order.
		{"anyof_null_number", `{"anyOf":[{"type":"null"},{"type":"number"}]}`, "*float64"},
		{"anyof_number_null", `{"anyOf":[{"type":"integer"},{"type":"null"}]}`, "*int"},
		{"anyof_null_ref", `{"anyOf":[{"type":"null"},{"$ref":"#/definitions/Ref"}]}`, "*Ref"},
		{"anyof_null_array", `{"anyOf":[{"type":"null"},{"type":"array","items":{"type":"string"}}]}`, "*[]string"},
		{"anyof_null_any", `{"anyOf":[{"type":"null"},{}]}`, "any"},
		{"anyof_three_way", `{"anyOf":[{"type":"null"},{"type":"string"},{"type":"integer"}]}`, "any"},

		// Constructs with no faithful Go mapping: degrade to any.
		{"oneOf", `{"oneOf":[{"type":"string"},{"type":"integer"}]}`, "any"},
		{"anyOf", `{"anyOf":[{"type":"string"},{"type":"boolean"}]}`, "any"},
		{"not", `{"not":{"type":"string"}}`, "any"},
		{"empty_schema", `{}`, "any"},
		{"boolean_schema_true", `true`, "any"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if got := optionalFieldType(t, tc.prop); got != tc.want {
				t.Errorf("type for %s = %q, want %q", tc.prop, got, tc.want)
			}
		})
	}
}

// TestGenerate_nullableScalars pins the presence-carrying contract around
// requiredness: a nullable scalar is a pointer whether the field is required
// or not (null is a legal VALUE — requiredness governs the json tag, never
// strips the pointer), and the optionality rule for objects cannot
// double-pointer it.
func TestGenerate_nullableScalars(t *testing.T) {
	schema := []byte(`{
		"type": "object",
		"required": ["min"],
		"properties": {
			"min": {"type": ["number", "null"]},
			"max": {"type": ["number", "null"]}
		}
	}`)
	src, err := gogen.Generate(schema, gogen.WithRootType("Root"))
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	if got := structFieldType(t, src, "Root", "Min"); got != "*float64" {
		t.Errorf("required nullable scalar = %q, want *float64", got)
	}
	if got := structFieldType(t, src, "Root", "Max"); got != "*float64" {
		t.Errorf("optional nullable scalar = %q, want *float64", got)
	}
}

// TestGenerate_nullableRoundTrip pins the two directions against each
// other: a Go pointer field, emitted as a schema under
// generate.WithNullablePointers (the anyOf:[null, T] shape), regenerates the
// same pointer field through Generate.
func TestGenerate_nullableRoundTrip(t *testing.T) {
	type Bounds struct {
		Minimum *float64 `json:"minimum"`
		Label   string   `json:"label"`
	}
	schema, err := generate.Generate(Bounds{}, generate.WithNullablePointers(true))
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	raw, err := json.Marshal(schema)
	if err != nil {
		t.Fatalf("marshal schema: %v", err)
	}
	src, err := gogen.Generate(raw, gogen.WithRootType("Bounds"))
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	if got := structFieldType(t, src, "Bounds", "Minimum"); got != "*float64" {
		t.Errorf("round-tripped pointer = %q, want *float64", got)
	}
	if got := structFieldType(t, src, "Bounds", "Label"); got != "string" {
		t.Errorf("round-tripped value = %q, want string", got)
	}
}

